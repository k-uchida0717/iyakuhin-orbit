/* 本文の重要語を目立たせる
   ・算定できない／禁忌／除く などの「してはいけない・対象外」… 赤
   ・〜に限る／のみ／ただし／併せて算定 などの「条件」… 黄
   ・数字＋単位（点・日・回・歳・mg など）と「月1回」「1日につき」などの回数制限 … 水色の太字
   HTML のタグ（検索語の <mark> やリンク）の外側の文字だけを置き換える。 */
"use strict";
const EMPH_RE=new RegExp([
  "(?<n>算定できない|算定しない|算定できません|認められない|禁忌|投与しないこと|使用しないこと|併用しないこと|行わないこと|適応外|対象外|算定の対象としない|を除く|を除き|除外)",
  "(?<c>に限り|に限る|に限って|に限定|のみ|以外の|以外は|ただし、|ただし|併せて算定|併算定|いずれか一方|主たるもの|所定点数に含まれ|別に算定|慎重に|注意すること|必要最小限)",
  "(?<f>(?:月|週|日|年)\\s?[0-9０-９]+\\s?回(?:に限り|まで)?|[0-9０-９]+\\s?日(?:につき|に1回)|1回に限り|[0-9０-９]+\\s?回に限り|初回に限り)",
  "(?<u>[0-9０-９]+(?:[.,．][0-9０-９]+)?\\s?(?:点|日間|日|回|歳|か月|ヶ月|箇月|週|時間|分|mg|μg|g|mL|L|%|単位|倍|割|円|床|名|人|kg|cm|mm|秒|分の[0-9０-９]+))"
].join("|"),"g");
function emph(html){
  if(!html)return html;
  return String(html).split(/(<[^>]+>)/).map((part,i)=>{
    if(i%2===1)return part; /* タグはそのまま */
    return part.replace(EMPH_RE,(m,...args)=>{
      const g=args[args.length-1];
      const cls=g.n?"em-n":g.c?"em-c":g.f?"em-f":"em-u";
      return`<span class="${cls}">${m}</span>`;
    });
  }).join("");
}
